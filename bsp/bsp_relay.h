/**
 * @file bsp_relay.h
 * @brief 板级继电器模块（IN ← PB0，**高电平触发**）。
 *
 * ── 接线 ────────────────────────────────────────────────────────────
 *   模块 IN   ── PB0            （高电平吸合，低电平断开）
 *   模块 VCC  ── 独立 5V 电源    （线圈电流 ~70–90 mA，不占板子 3.3V 轨）
 *   模块 GND  ── 板子 GND        ⚠️ **必须共地**，否则 PB0 的 3.3V
 *                                 对模块而言没有参考电平，永远"没信号"
 *   模块 COM  ── 12V+
 *   模块 NO   ── 小灯模块正极     （灯负极回 12V 电源 GND）
 * ────────────────────────────────────────────────────────────────────
 *
 * ── 为什么 PB0 可以直接驱动 IN ──────────────────────────────────────
 *   IN 接的是模块板载三极管/光耦的输入，是高阻的；真正吃电流的线圈
 *   由模块自己用 VCC（5V）驱动。所以 MCU 侧只是给一个电平，不是给功率。
 *
 * ── 为什么要独立 5V ─────────────────────────────────────────────────
 *   线圈那 70–90 mA 若压在板子的 3.3V 轨上，会和 OLED、蜂鸣器抢余量。
 *   新增负载尽量不往 3.3V 轨上叠：负载跳变引起的电源跌落，
 *   静态测量是看不出来的。
 *
 * 初始电平由 CubeMX 生成的 MX_GPIO_Init() 置为**低**（断开），
 * 上电瞬间继电器不会动作。
 */
#ifndef BSP_RELAY_H
#define BSP_RELAY_H

#include <stdbool.h>

#include "interface/error.h"

/**
 * @brief 初始化（登记状态）。
 *
 * **不配置引脚**——引脚模式（推挽输出 + 初始低）由 CubeMX 生成的
 * MX_GPIO_Init() 完成。因此必须在它**之后**调用。
 *
 * @return error_t ERR_OK 成功。
 */
error_t bsp_relay_init(void);

/**
 * @brief 吸合 / 断开继电器。
 *
 * @param on true = 吸合（COM–NO 导通，小灯亮）；false = 断开。
 *
 * @return error_t ERR_OK 成功；ERR_NOT_INITIALIZED 还没初始化。
 */
error_t bsp_relay_set(bool on);

/**
 * @brief 取继电器当前的命令状态。
 *
 * @return bool true 表示当前命令是吸合。**这是命令值，不是触点实测状态**：
 *              继电器机械动作有几毫秒延迟，且触点可能粘连，本层无法感知。
 */
bool bsp_relay_is_on(void);

#endif /* BSP_RELAY_H */
