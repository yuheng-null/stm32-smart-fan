/**
 * @file bsp_ir.h
 * @brief 板级红外接收头（VS1838B，OUT → PC7）支持。
 *
 * ── 接线 ────────────────────────────────────────────────────────────
 *   模块丝印        接到
 *   -----------     ----------------
 *   OUT        ──   PC7        （EXTI7，双边沿中断，内部上拉）
 *   GND        ──   GND
 *   VCC        ──   3V3        （VS1838B 支持 2.7~5.5V，接 3.3V 与 MCU 同电平）
 *
 *   ⚠️ **引脚顺序按丝印核对，别按位置猜**。这一颗常见封装是「镜头朝自己、
 *      左→右 = OUT / GND / VCC」，但不同厂家的仿制品确实有排法不同的，
 *      而且没有防反接——接错位置等于把 VCC 灌进 OUT。三根线用万用表对一下
 *      地就行：GND 与板子地是通的。
 *
 *   上拉：VS1838B 的 OUT 需要上拉。模块多半板载了一只（常见 10 kΩ）；
 *   没有的话靠 PC7 的内部上拉（约 40 kΩ）也能工作，但边沿会变缓，
 *   信号质量要求高时在 PC7 与 3V3 之间补一只 10 kΩ。
 *
 * ── 这一层做什么、不做什么 ──────────────────────────────────────────
 *   **只做**：中断里把「边沿之后的电平 + 边沿时刻」存进一个环形缓冲，
 *   由主循环取走。
 *   **不做**：协议解码。NEC 的时序判定、反码校验全在
 *   `module/ir_remote/` 里（纯计算、可在 PC 上单测）。
 *
 *   这条分工与风扇那边一致：`bsp_fan` 只交出「FG 周期」这个物理量，
 *   「周期 → 转速」的换算留给 app 去调 `module/fan_control`。
 *   BSP 一旦开始解析协议，换协议就要动硬件层，而硬件层本该是最不该动的那层。
 *
 * ── 为什么中断里只搬数据、不解码 ────────────────────────────────────
 *   一帧 NEC 有 68 个边沿，解一位要比较若干个时间窗口。把这些放进中断里，
 *   中断会长时间占着 CPU，串口与 FG 捕获都得等它——而它们丢的是**真数据**。
 *   所以中断只做两件事：读电平、读时刻、入队。剩下的在主循环里从容做完。
 *   顺带一提：环形缓冲是单生产者（中断）单消费者（主循环），
 *   不需要临界区就能保证一致——这是它比队列更省事的地方。
 */
#ifndef BSP_IR_H
#define BSP_IR_H

#include <stdbool.h>
#include <stdint.h>

#include "interface/error.h"

/** 一次边沿：电平与发生时刻。与 module/ir_remote 的输入约定一一对应。 */
typedef struct {
    uint32_t us;      /**< 边沿发生的时刻（bsp_time_us 的值） */
    bool     level;   /**< 边沿**之后**的电平（true = 高） */
} bsp_ir_edge_t;

/**
 * @brief 初始化：清空缓冲，允许中断开始收边沿。
 *
 * ⚠️ 必须在 bsp_fan_init() 之后调用——边沿时刻取自 TIM2 的计数器，
 *    那个计数器是在 bsp_fan_init() 里启动的。
 *
 * @return error_t ERR_OK；ERR_NOT_INITIALIZED 时基尚未就绪（bsp_fan 没初始化）。
 */
error_t bsp_ir_init(void);

/**
 * @brief 取一个边沿（主循环调用）。
 *
 * @param out 取到时填入。
 * @return true 取到一个边沿；false 缓冲已空。
 *
 * @note 取不到就马上返回，不做任何等待——它是在任务里被周期性调用的。
 */
bool bsp_ir_take_edge(bsp_ir_edge_t *out);

/**
 * @brief 因为缓冲满而被丢掉的边沿数。
 *
 * 稳态下应当恒为 0。持续增长说明主循环被长时间阻塞（或线上有持续的干扰），
 * 此时丢的是**真数据**，遥控会变得时灵时不灵——所以这个数要能看见。
 *
 * @return uint32_t 累计丢弃数。
 */
uint32_t bsp_ir_get_dropped(void);

/**
 * @brief 丢弃缓冲里所有待处理的边沿（不影响累计丢弃数）。
 *
 * 用在「刚经历了一段不关心的时间」之后，例如学习模式开关切换时。
 */
void bsp_ir_flush(void);

#endif /* BSP_IR_H */
