/**
 * @file bsp_time.h
 * @brief 系统微秒时基。
 *
 * ── 为什么需要它 ────────────────────────────────────────────────────
 *   SysTick 给的是 **1 ms** 的节拍（bsp_system_get_tick_ms），对温控、按键、
 *   遥测都够用。但有些信号的**特征在微秒量级**——红外遥控 NEC 协议里，
 *   一位的宽度只有 0.56 ms，判「是 0 还是 1」看的是 0.56 ms 与 1.69 ms 之差。
 *   1 ms 的节拍分不出来，必须有一个更细的时基。
 *
 * ── 用的是什么 ──────────────────────────────────────────────────────
 *   **TIM2 的自由运行计数器**。它本来就是为 FG 测速配成 1 MHz、32 位的
 *   （PSC = 83，APB1 定时器时钟 84 MHz），32 位 @1 MHz 要 **4295 秒**才回绕，
 *   做时基绰绰有余；复用它比再占一个定时器省一个外设、也省一组配置。
 *
 * ⚠️ 因此有两条使用前提：
 *   1. **必须在 bsp_fan_init() 之后用**——计数器是在那里启动的
 *      （HAL_TIM_IC_Start_IT）。在那之前读到的恒为 0。
 *   2. TIM2 的配置归 bsp_fan 管（那是它捕获 FG 用的定时器）。本模块只**读**
 *      它的计数器，不碰它的任何配置。
 *
 * ── 为什么是函数而不是宏 ────────────────────────────────────────────
 *   计数 → 微秒的换算依赖 PSC 与定时器时钟，两者都对配置敏感。做成函数、
 *   运行期算，`.ioc` 里改了 PSC 也不会静默偏掉（同 bsp_fan 的理由）。
 */
#ifndef BSP_TIME_H
#define BSP_TIME_H

#include <stdint.h>

/**
 * @brief TIM2 计数器的频率（Hz）。
 *
 * bsp_fan 用它把 FG 捕获到的计数换算成微秒；本模块用它把计数器换算成微秒。
 * 两处共用这一个函数，是为了让「TIM2 到底跑多快」只有**一处**说法——
 * 同一份事实写两遍，改配置时必然漂移。
 *
 * @return uint32_t 计数频率（本板为 1000000）。
 */
uint32_t bsp_time_counter_hz(void);

/**
 * @brief 系统微秒时基的当前值。
 *
 * @return uint32_t 微秒计数；32 位、约 4295 秒回绕一次。
 *
 * @note 调用方若用两个时刻相减，请用**无符号减法**——回绕时结果依然正确。
 * @note 必须在 bsp_fan_init() 之后调用（见文件头）。
 */
uint32_t bsp_time_us(void);

#endif /* BSP_TIME_H */
